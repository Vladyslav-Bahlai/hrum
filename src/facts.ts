/** Факт про ингредиенты блюда: сначала от ИИ, потом из словаря, потом по составу КБЖУ. */
export function factFor(it: FoodItem): string {
  if (it.fact && it.fact.trim()) return it.fact.trim();
  const hay = `${it.name} ${it.note || ''}`.toLowerCase();
  for (const [re, f] of FACTS) if (re.test(hay)) return f;
  const k = known(it);
  if (k.protein && (it.protein || 0) >= 20) return `В порции около ${Math.round(it.protein!)} г белка — это примерно треть суточной нормы.`;
  if (k.fat && (it.fat || 0) >= 25) return `Основной вклад в калории здесь дают жиры: около ${Math.round(it.fat!)} г на порцию.`;
  if (k.carbs && (it.carbs || 0) >= 50) return `Много углеводов (${Math.round(it.carbs!)} г) — это быстрая энергия на несколько часов.`;
  return 'Хорошо жевать медленно: сигнал сытости доходит до мозга примерно через 15–20 минут.';
}
