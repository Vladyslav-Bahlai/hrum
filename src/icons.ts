const ADJ = /(ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ую|юю|ых|их|ым|им|ыми|ими|ною|ный|ная|ное|ные|ський|ська|ське|ські|ний|на|не|ні)$/;

const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[«»"'`.,!?;:()\[\]{}\/\\|+*&%№#–—-]/g, ' ').replace(/\s+/g, ' ').trim();
const looksAdj = (w: string) => !NOUN_LIKE.has(w) && w.length > 3 && /[а-яіїєґ]/.test(w) && ADJ.test(w);

interface Compiled { emoji: string; stem: string; multi: boolean; en?: string }
let compiled: Compiled[] | null = null;
const compile = (): Compiled[] => {
  if (compiled) return compiled;
  const out: Compiled[] = [];
  for (const [emoji, stems] of RULES) for (const raw of stems) {
    const [st, en] = raw.split('=');
    const stem = norm(st);
    if (stem) out.push({ emoji, stem, multi: stem.includes(' '), en: en?.trim() || undefined });
  }
  compiled = out;
  return out;
};

/** Сколько всего ключевых слов в библиотеке (для тестов/справки). */
export const keywordCount = () => compile().length;
/** Все эмодзи библиотеки. */
export const allIcons = () => Array.from(new Set(RULES.map((r) => r[0])));

/** Лучшее совпадение по библиотеке или undefined. */
export function matchIcon(name: string): string | undefined {
  return matchDish(name)?.emoji;
}

/** Лучшее совпадение: эмодзи и английское название для поиска картинки (если задано у основы). */
export function matchDish(name: string): { emoji: string; en?: string } | undefined {
  const s = norm(name || '');
  if (!s) return undefined;
  const words = s.split(' ').filter(Boolean);
  const prepAt = words.findIndex((w, i) => i > 0 && PREPS.has(w));
  const mainEnd = prepAt < 0 ? words.length : prepAt;
  // главное слово — первое «не-прилагательное» до первого предлога
  let head = -1;
  for (let i = 0; i < mainEnd; i++) if (!looksAdj(words[i]) && !PREPS.has(words[i])) { head = i; break; }
  if (head < 0) head = 0;
  let best: { emoji: string; score: number; en?: string } | undefined;
  const consider = (emoji: string, score: number, en?: string) => { if (!best || score > best.score) best = { emoji, score, en }; };
  for (const r of compile()) {
    if (r.multi) {
      const at = s.indexOf(r.stem);
      if (at >= 0 && (at === 0 || s[at - 1] === ' ')) {
        const wi = s.slice(0, at).split(' ').filter(Boolean).length;
        consider(r.emoji, r.stem.length + 4 + (wi === head ? 30 : 0) + (wi < mainEnd ? 15 : 0) - wi * 0.5, r.en);
      }
      continue;
    }
    for (let i = 0; i < words.length; i++) {
      const w = words[i];
      if (!w.startsWith(r.stem)) continue;
      // очень короткие основы (2–3 буквы) — только целым словом или с коротким окончанием
      if (r.stem.length <= 3 && w.length - r.stem.length > 3) continue;
      consider(r.emoji, r.stem.length + (i === head ? 30 : 0) + (i < mainEnd ? 15 : 0) - i * 0.5, r.en);
    }
  }
  return best ? { emoji: best.emoji, en: best.en } : undefined;
}

/** Иконка блюда: библиотека по названию → эмодзи от ИИ → 🍽️. */
export function iconFor(name: string, fallback?: string): string {
  return matchIcon(name) || (fallback && fallback !== DEFAULT_ICON ? fallback : '') || DEFAULT_ICON;
}

/** Кодпоинты эмодзи как в именах файлов OpenMoji («1F35D», «1F37D»), без вариационного селектора FE0F. */
export const emojiHex = (e: string) => Array.from(e).map((c) => c.codePointAt(0)!).filter((c) => c !== 0xfe0f).map((c) => c.toString(16).toUpperCase()).join('-');
